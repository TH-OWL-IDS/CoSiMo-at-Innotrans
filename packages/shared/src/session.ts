/**
 * Session & turn records — the RUNTIME-generated research dataset. Written live
 * by the realtime service into Payload's `sessions` collection; read-only in
 * the admin. Structured turns only — never audio (GDPR).
 */

import type { FaceEmotion } from "./emotion.js";
import type { PersonaKey } from "./persona.js";
import type { CabinControlId } from "./cabin.js";
import type { Locale } from "./telemetry.js";

export type Modality = "voice" | "text";
export type TurnRole = "user" | "cosimo";
export type TurnOutcome =
  | "ok"
  | "not_understood"
  | "error"
  | "offline_canned"
  /** The rider barged in (talk button / new input) and the turn was aborted. */
  | "interrupted";

export interface TurnAction {
  /** Which tool CoSiMo invoked, if any (e.g. "set_light"). */
  tool: string;
  /** Target control, when the action was a cabin control. */
  control?: CabinControlId;
  /** Serialized arguments, for later analysis. */
  args?: Record<string, unknown>;
  /** What the tool returned to the model (truncated), and whether it worked. */
  result?: string;
  ok?: boolean;
  durationMs?: number;
}

export interface Turn {
  role: TurnRole;
  modality: Modality;
  lang: Locale;
  /** What was said/typed or spoken back. No audio is stored. */
  transcript: string;
  /** Classified intent for the user turn (e.g. "ask_eta", "command_light"). */
  detectedIntent?: string;
  /** @deprecated Last action only — kept for old rows. Use `actions`. */
  action?: TurnAction;
  /** Every tool call of a cosimo turn, in order (incl. set_emotion). */
  actions?: TurnAction[];
  /** The brain that answered (absent for canned turns). */
  llm?: { provider: string; model: string };
  /** Where the latency went. */
  timings?: { sttMs?: number; llmMs?: number; ttsMs?: number };
  /** The error message when outcome is "error". */
  error?: string;
  /** Face emotion CoSiMo displayed during this turn. */
  faceEmotion?: FaceEmotion;
  /** End-to-end latency for a cosimo turn, in milliseconds. */
  latencyMs?: number;
  outcome?: TurnOutcome;
  /** ISO timestamp; stamped by the realtime service. */
  at: string;
}

export interface SessionRecord {
  /** Stable session id (generated by realtime). */
  sessionId: string;
  /** Which iPad/device this conversation happened on. */
  deviceId: string;
  persona: PersonaKey;
  /** Whether the visitor consented to recording (gates persistence detail). */
  consent: boolean;
  startedAt: string;
  endedAt?: string;
  turns: Turn[];
}
